"""Function maps for ps2_recomp, built from RGDecomp's symbol files.

ps2_recomp reads a Ghidra-style CSV (`Name,Start,End,Size`, End exclusive)
through `ghidra_output`. One map per image: the main ELF and each real MWo3
overlay. The maps are RGDecomp's `config/<image>.symbols.txt` (functions only)
plus the corrections in `config/<version>/funcmap.toml`.

Naming: every name ends in its own address (`sceCdRead_12a728`). ps2_recomp
binds any function whose name equals a runtime handler (`sceCdRead`) to that
handler on its own, so bare SDK names would bind silently; with the suffix
nothing binds unless `[general].stubs` in the recompiler config says so.
"""

from __future__ import annotations

import csv
import re
from dataclasses import dataclass
from pathlib import Path

# The recompiler treats these as its own placeholder names (elf_parser.cpp
# IsAutoGeneratedName, ps2_recompiler.cpp isEntryFunctionName): map rows with
# them lose their authority over bounds, or are taken for synthesized entries.
RESERVED_PREFIXES = ("sub_", "FUN_", "LAB_", "DAT_", "entry_")

_SYMBOL = re.compile(r"^\s*([A-Za-z_.$][\w.$]*)\s*=\s*(0x[0-9A-Fa-f]+)\s*;\s*(?://(.*))?$")
_SIZE = re.compile(r"\bsize:(0x[0-9A-Fa-f]+)")
_ADDR_SUFFIX = re.compile(r"_([0-9a-fA-F]{6,8})$")


@dataclass(frozen=True)
class Function:
    name: str
    start: int
    end: int  # exclusive

    @property
    def size(self) -> int:
        return self.end - self.start


def read_rgdecomp(path: Path) -> list[Function]:
    """Functions (`// type:func size:..`) from an RGDecomp *.symbols.txt."""
    out = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        m = _SYMBOL.match(s)
        if not m:
            raise ValueError(f"{path.name}:{lineno}: cannot parse {s!r}")
        comment = m.group(3) or ""
        if "type:func" not in comment:
            continue
        size = _SIZE.search(comment)
        if not size:
            raise ValueError(f"{path.name}:{lineno}: function without size")
        start = int(m.group(2), 16)
        out.append(Function(m.group(1), start, start + int(size.group(1), 16)))
    return out


def csv_name(name: str, start: int, prefix: str = "") -> str:
    """Apply the naming policy: optional image prefix, address suffix, no reserved prefix."""
    if prefix and not name.startswith(prefix):
        name = prefix + name
    m = _ADDR_SUFFIX.search(name)
    if not (m and int(m.group(1), 16) == start):
        name = f"{name}_{start:06x}"
    if name.startswith("entry"):  # RGDecomp's `entry` would become `entry_100008`
        name = "rg_" + name
    return name


def read_csv(path: Path) -> list[Function]:
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    if not rows or rows[0] != ["Name", "Start", "End", "Size"]:
        raise ValueError(f"{path}: not a Name,Start,End,Size map")
    out = []
    for row in rows[1:]:
        name, start, end, size = row
        fn = Function(name, int(start, 16), int(end, 16))
        if fn.size != int(size):
            raise ValueError(f"{path}: {name}: size {size} does not match {start}..{end}")
        out.append(fn)
    return out


def write_csv(path: Path, funcs: list[Function]) -> None:
    lines = ["Name,Start,End,Size"]
    lines += [f"{f.name},0x{f.start:08X},0x{f.end:08X},{f.size}" for f in funcs]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def _range(entry: dict, key: str = "range") -> tuple[int, int]:
    lo, hi = entry[key]
    if hi <= lo:
        raise ValueError(f"empty range {lo:#x}..{hi:#x}")
    return lo, hi


def build(image: str, spec: dict, rgd: list[Function]) -> tuple[list[Function], list[str]]:
    """Apply one image's corrections from funcmap.toml. Returns (map, log lines)."""
    prefix = "" if image == "main" else image + "_"
    by_start = {f.start: f for f in rgd}
    if len(by_start) != len(rgd):
        raise ValueError(f"{image}: duplicate start addresses in RGDecomp symbols")
    log = []

    for rm in spec.get("remove", []):
        lo, hi = _range(rm)
        gone = [s for s in by_start if lo <= s < hi]
        if not gone:
            raise ValueError(f"{image}: remove {lo:#x}..{hi:#x} matches nothing")
        for s in gone:
            del by_start[s]
        log.append(f"removed {len(gone)} in {lo:#010x}..{hi:#010x}")

    for rs in spec.get("resize", []):
        f = by_start.get(rs["start"])
        if f is None:
            raise ValueError(f"{image}: resize {rs['start']:#x}: no such function")
        by_start[f.start] = Function(f.name, f.start, rs["end"])
        log.append(f"resized {f.name} to {f.start:#010x}..{rs['end']:#010x}")

    added = [(a["name"], *_range(a)) for a in spec.get("add", [])]
    added += [("StaticInit", lo, hi) for lo, hi in spec.get("static_init", [])]
    for name, lo, hi in added:
        if lo in by_start:
            raise ValueError(f"{image}: add {lo:#x}: already a function")
        by_start[lo] = Function(name, lo, hi)
    if added:
        log.append(f"added {len(added)}")

    funcs = sorted(
        (Function(csv_name(f.name, f.start, prefix), f.start, f.end) for f in by_start.values()),
        key=lambda f: f.start,
    )
    for a, b in zip(funcs, funcs[1:]):
        if a.end > b.start:
            raise ValueError(f"{image}: {a.name} ({a.start:#x}..{a.end:#x}) overlaps {b.name}")
    names = [f.name for f in funcs]
    if len(set(names)) != len(names):
        raise ValueError(f"{image}: duplicate names after renaming")
    return funcs, log
